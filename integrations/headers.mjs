/**
 * Writes dist/_headers: the response headers Cloudflare sends with every file.
 * They cover what a <meta> tag can't: HSTS, nosniff, framing and so on.
 *
 * Builds of `master` are prod. Every other build (dev, branch previews, local)
 * also tells search engines not to index it. Set SITE_ENV=prod or SITE_ENV=dev
 * to override.
 */
import { writeFile } from 'node:fs/promises';

/** @param {NodeJS.ProcessEnv} [env] */
export function siteEnv(env = process.env) {
  if (env.SITE_ENV === 'prod' || env.SITE_ENV === 'dev') return env.SITE_ENV;
  return env.WORKERS_CI_BRANCH === 'master' ? 'prod' : 'dev';
}

const EVERY_PAGE = [
  'Strict-Transport-Security: max-age=31536000',
  'X-Content-Type-Options: nosniff',
  'X-Frame-Options: DENY',
  // Joins the <meta> policy; frame-ancestors only works as a header.
  "Content-Security-Policy: frame-ancestors 'none'",
  'Referrer-Policy: strict-origin-when-cross-origin',
  'Permissions-Policy: accelerometer=(), browsing-topics=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()',
  'Cross-Origin-Opener-Policy: same-origin',
];

/** @param {'prod' | 'dev'} env */
export function headersFile(env) {
  const page = env === 'prod' ? EVERY_PAGE : [...EVERY_PAGE, 'X-Robots-Tag: noindex, nofollow'];
  const block = (/** @type {string} */ path, /** @type {string[]} */ lines) =>
    [path, ...lines.map((l) => `  ${l}`)].join('\n');
  return [
    `# Generated by integrations/headers.mjs for ${env}. Do not edit.`,
    block('/*', page),
    // Astro fingerprints everything in /_astro/, so it never changes in place.
    block('/_astro/*', ['Cache-Control: public, max-age=31536000, immutable']),
    '',
  ].join('\n\n');
}

/** @returns {import('astro').AstroIntegration} */
export default function headers() {
  return {
    name: 'headers',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const env = siteEnv();
        await writeFile(new URL('_headers', dir), headersFile(env));
        logger.info(`Wrote _headers for ${env}`);
      },
    },
  };
}
